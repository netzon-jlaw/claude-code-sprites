/**
 * Exporters. Each takes a Sprite and returns either a string or a Buffer.
 */
import { PNG } from "pngjs";
import type { Sprite } from "../core/sprite.js";
import { renderLines, renderPlain, type ColorMode } from "../core/render.js";
import { resolveSprite } from "../core/resolve.js";
import { hexToRgb } from "../core/color.js";

export type ExportFormat = "ansi" | "sh" | "js" | "ts" | "py" | "png" | "html" | "txt";
export const EXPORT_FORMATS: readonly ExportFormat[] = ["ansi", "sh", "js", "ts", "py", "png", "html", "txt"];

export interface ExportOptions {
  colorMode?: ColorMode;
  /** PNG: pixels per sprite pixel. */
  scale?: number;
  /** PNG: background colour; omitted = transparent. */
  background?: string;
  /** js/ts/py: variable name. */
  varName?: string;
  /** html: wrap in a <pre>. */
  pre?: boolean;
}

export function exportSprite(s: Sprite, format: ExportFormat, opts: ExportOptions = {}): string | Buffer {
  switch (format) {
    case "ansi": return exportAnsi(s, opts);
    case "txt": return renderPlain(s);
    case "sh": return exportShell(s, opts);
    case "js": return exportJs(s, opts, false);
    case "ts": return exportJs(s, opts, true);
    case "py": return exportPython(s, opts);
    case "html": return exportHtml(s, opts);
    case "png": return exportPng(s, opts);
  }
}

export function extensionFor(format: ExportFormat): string {
  return { ansi: ".ans", txt: ".txt", sh: ".sh", js: ".js", ts: ".ts", py: ".py", html: ".html", png: ".png" }[format];
}

export function exportAnsi(s: Sprite, opts: ExportOptions): string {
  return renderLines(s, { colorMode: opts.colorMode ?? "truecolor" }).join("\n") + "\n";
}

/** Escape a rendered line for a double-quoted JS/Python string literal. */
function escapeForLiteral(line: string): string {
  return line.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\x1b/g, "\\x1b");
}

function safeName(name: string | undefined, fallback: string): string {
  const n = (name ?? fallback).replace(/[^A-Za-z0-9_]/g, "_").replace(/^(\d)/, "_$1");
  return n || fallback;
}

export function exportShell(s: Sprite, opts: ExportOptions): string {
  const lines = renderLines(s, { colorMode: opts.colorMode ?? "truecolor" });
  const body = lines.map((l) => {
    // printf format strings: escape % and backslashes, use \033 for ESC.
    const esc = l.replace(/\\/g, "\\\\").replace(/%/g, "%%").replace(/'/g, "'\\''").replace(/\x1b/g, "\\033");
    return `printf '${esc}\\n'`;
  });
  return ["#!/bin/sh", `# ${s.name ?? "sprite"} ${s.width}x${s.height} (${s.mode})`, ...body, ""].join("\n");
}

export function exportJs(s: Sprite, opts: ExportOptions, ts: boolean): string {
  const lines = renderLines(s, { colorMode: opts.colorMode ?? "truecolor" });
  const name = safeName(opts.varName ?? s.name, "SPRITE").toUpperCase();
  const typed = ts ? ": string" : "";
  const body = lines.map((l) => `  "${escapeForLiteral(l)}"`).join(",\n");
  return `// ${s.name ?? "sprite"} ${s.width}x${s.height} (${s.mode}) — generated by unicode-sprite\nexport const ${name}${typed} = [\n${body},\n].join("\\n");\n`;
}

export function exportPython(s: Sprite, opts: ExportOptions): string {
  const lines = renderLines(s, { colorMode: opts.colorMode ?? "truecolor" });
  const name = safeName(opts.varName ?? s.name, "SPRITE").toUpperCase();
  const body = lines.map((l) => `    "${escapeForLiteral(l)}"`).join(",\n");
  return `# ${s.name ?? "sprite"} ${s.width}x${s.height} (${s.mode}) — generated by unicode-sprite\n${name} = "\\n".join([\n${body},\n])\n`;
}

function escapeHtml(t: string): string {
  return t.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

export function exportHtml(s: Sprite, opts: ExportOptions): string {
  const rows = resolveSprite(s).map((row) => {
    let out = "";
    let open: string | null = null;
    let run = "";
    const flush = () => {
      if (!run) return;
      out += open ? `<span style="${open}">${escapeHtml(run)}</span>` : escapeHtml(run);
      run = "";
    };
    for (const c of row) {
      const style = c.ch === " " && !c.bg ? null : [c.fg && c.ch !== " " ? `color:${c.fg}` : "", c.bg ? `background:${c.bg}` : ""].filter(Boolean).join(";");
      const key = style || null;
      if (key !== open) { flush(); open = key; }
      run += c.ch;
    }
    flush();
    return out;
  });
  const inner = rows.join("\n");
  return opts.pre === false ? inner + "\n" : `<pre style="font-family:monospace;line-height:1;margin:0">${inner}</pre>\n`;
}

export function exportPng(s: Sprite, opts: ExportOptions): Buffer {
  const scale = Math.max(1, Math.floor(opts.scale ?? 8));
  // Each pixel is drawn as scale x (scale*aspect) so the image matches the terminal look.
  // Terminal cells are roughly 1:2, so in half mode a pixel is square-ish; in quadrant mode it is too.
  const png = new PNG({ width: s.width * scale, height: s.height * scale });
  const bg = opts.background ? hexToRgb(opts.background) : null;
  const cells = resolveSprite(s);
  for (let y = 0; y < s.height; y++) {
    for (let x = 0; x < s.width; x++) {
      // Use the resolved (merged) colour so the PNG matches what the terminal shows.
      const cx = s.mode === "half" ? x : x >> 1;
      const cy = y >> 1;
      const idx = s.mode === "half" ? y & 1 : (x & 1) | ((y & 1) << 1);
      const p = cells[cy][cx].shown[idx];
      const rgb = p ? hexToRgb(p) : bg;
      const alpha = p || bg ? 255 : 0;
      for (let dy = 0; dy < scale; dy++) {
        for (let dx = 0; dx < scale; dx++) {
          const i = ((y * scale + dy) * png.width + (x * scale + dx)) * 4;
          png.data[i] = rgb?.r ?? 0;
          png.data[i + 1] = rgb?.g ?? 0;
          png.data[i + 2] = rgb?.b ?? 0;
          png.data[i + 3] = alpha;
        }
      }
    }
  }
  return PNG.sync.write(png);
}
