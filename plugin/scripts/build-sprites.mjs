// Compiles the seven party sprites from the repository's example sprites
// into ../hooks/sprites.ts: one flat body color and the eye color per figure,
// 16 pixels wide, in the style of the Claude Code mascot.
//
//   node plugin/scripts/build-sprites.mjs [sprites dir] [preview.ppm]
//
// The sprites dir defaults to the repository's examples/. Run it again
// whenever one of the seven changes. The sources are the `.sprite.json` files
// the unicode-sprite CLI writes: rows of space-separated palette keys, `-`
// for transparent.
import { readFile, writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';

const SRC = process.argv[2] ? pathToFileURL(`${process.argv[2].replace(/\/$/, '')}/`) : new URL('../../examples/', import.meta.url);
const OUT = new URL('../hooks/sprites.ts', import.meta.url);
const PREVIEW = process.argv[3];
/** Class → sprite, in class index order (see classOf in register.tsx). */
const CLASSES = [
  ['Front-end', 'diamond'],
  ['Back-end', 'rocket'],
  ['UX Design', 'bunny'],
  ['Cloud & DevOps', 'clover'],
  ['Data Engineering', 'crab'],
  ['Security & Governance', 'crown'],
  ['Project Management', 'lemon'],
];
const EYE = '#2A1A14';
const KEYS = '0123456789abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ';
const palette = [];
const index = (hex) => { let i = palette.indexOf(hex); if (i < 0) { palette.push(hex); i = palette.length - 1; } return i; };
const sprites = [];
for (const [cls, name] of CLASSES) {
  const src = JSON.parse(await readFile(new URL(`${name}.sprite.json`, SRC), 'utf8'));
  if (src.mode !== 'quadrant' || src.width !== 16) throw new Error(`${name}: expected a 16-wide quadrant sprite`);
  const colors = Object.fromEntries(Object.entries(src.palette).map(([k, hex]) => [k, hex.toUpperCase()]));
  const bodies = new Set(Object.values(colors).filter((hex) => hex !== EYE));
  if (bodies.size !== 1 || !Object.values(colors).includes(EYE)) throw new Error(`${name}: expected one body color and the eye color ${EYE}`);
  const rows = src.pixels.map((row, y) => {
    const toks = typeof row === 'string' ? row.trim().split(/\s+/) : row;
    if (toks.length !== src.width) throw new Error(`${name}: row ${y} has ${toks.length} pixels, not ${src.width}`);
    return toks.map((t) => (t === '-' || t === null ? '.' : KEYS[index(colors[t] ?? t.toUpperCase())])).join('');
  });
  sprites.push({ cls, name, w: src.width, h: src.height, feet: src.height, rows });
}
if (palette.length > KEYS.length) throw new Error('too many colors');
const ts = `// Generated by the sprite-party plugin's sprite build
// (plugin/scripts/build-sprites.mjs) from the repository's examples/: the
// seven party sprites, one flat body color and the eye color each.
// Regenerate rather than edit.
export type Sprite = { cls: string; name: string; w: number; h: number; feet: number; rows: string[] }
export const EYE = ${JSON.stringify(EYE)}
export const PALETTE: string[] = ${JSON.stringify(palette)}
export const KEYS = ${JSON.stringify(KEYS)}
export const SPRITES: Sprite[] = ${JSON.stringify(sprites, null, 1)}
`;
await writeFile(OUT, ts);
console.log(sprites.map((s) => `${s.cls}: ${s.name} ${s.w}x${s.h}`).join('\n'), '\ncolors:', palette.length);
if (PREVIEW) {
  // A binary PPM (no dependencies): every mascot in a row on a light ground.
  const SCALE = 4, GAP = 2;
  const W = sprites.reduce((a, s) => a + s.w + GAP, GAP) * SCALE, H = (Math.max(...sprites.map((s) => s.h)) + GAP * 2) * SCALE;
  const rgb = Buffer.alloc(W * H * 3);
  for (let i = 0; i < W * H; i++) rgb.set([0xe9, 0xdc, 0xc6], i * 3);
  let ox = GAP;
  for (const s of sprites) {
    s.rows.forEach((row, y) => {
      [...row].forEach((ch, x) => {
        if (ch === '.') return;
        const hex = palette[KEYS.indexOf(ch)];
        const px = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16));
        for (let dy = 0; dy < SCALE; dy++) for (let dx = 0; dx < SCALE; dx++) {
          rgb.set(px, (((GAP + y) * SCALE + dy) * W + (ox + x) * SCALE + dx) * 3);
        }
      });
    });
    ox += s.w + GAP;
  }
  await writeFile(PREVIEW, Buffer.concat([Buffer.from(`P6\n${W} ${H}\n255\n`), rgb]));
}
